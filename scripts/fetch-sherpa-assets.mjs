#!/usr/bin/env node
/** Downloads everything on-device listening needs and writes a folder to serve.
 *
 *   node scripts/fetch-sherpa-assets.mjs [output-folder] [--runtime-version=X.Y.Z] [--runtime-dir=PATH]
 *
 * --runtime-dir uses a sherpa-onnx WebAssembly build you made yourself
 * (build-wasm-simd-web.sh) instead of downloading the published one.
 *
 * Output (default ./sherpa-assets, ~60 MB):
 *   runtime/  sherpa-onnx WebAssembly runtime + two isolated JS API files
 *   models/   Silero voice detection + streaming English Zipformer (int8)
 *   manifest.json  file paths, sizes and Subresource Integrity hashes
 *
 * Serve the folder from your own origin and pass its URL as assetBaseUrl.
 * Requires Node 22+, network access and a `tar` that handles .tar.gz/.tar.bz2.
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { cp, mkdir, mkdtemp, readFile, readdir, rm, writeFile, copyFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const MODELS = 'https://github.com/k2-fsa/sherpa-onnx/releases/download/asr-models';
const ASR_NAME = 'sherpa-onnx-streaming-zipformer-en-20M-2023-02-17';
const PUB_PACKAGE = 'https://pub.dev/api/packages/sherpa_onnx_web';

/** Wraps a sherpa-onnx browser API script so its helper functions cannot collide
 * with another wrapper's when both are loaded into the same worker. */
export function wrapClassicApi(source, globalName, names) {
  if (!/^[A-Za-z_$][\w$]*$/.test(globalName) || !names.every(name => /^[A-Za-z_$][\w$]*$/.test(name))) throw new TypeError('Invalid API names.');
  for (const name of names) if (!new RegExp(`function\\s+${name}\\s*\\(`).test(source)) throw new Error(`The sherpa-onnx API file does not define ${name}().`);
  return `/* Isolated copy generated by Conversation-Agent from sherpa-onnx (Apache-2.0). */\n`
    // Shadowing the CommonJS names keeps the browser code path in every environment.
    + `self.${globalName} = (function (process, module, exports, require) {\n${source}\n;return { ${names.join(', ')} };\n}).call(self);\n`;
}

const sri = data => `sha384-${createHash('sha384').update(data).digest('base64')}`;

async function download(url, target, headers = {}) {
  const response = await fetch(url, { headers, redirect: 'follow' });
  if (!response.ok) throw new Error(`Download failed (${response.status}): ${url}`);
  const data = Buffer.from(await response.arrayBuffer());
  await writeFile(target, data);
  return data;
}

async function findFile(folder, name) {
  for (const entry of await readdir(folder, { withFileTypes: true, recursive: true })) {
    if (entry.isFile() && entry.name === name) return join(entry.parentPath ?? entry.path, entry.name);
  }
  throw new Error(`${name} was not found in the downloaded package.`);
}

async function main() {
  const args = process.argv.slice(2);
  const out = resolve(args.find(arg => !arg.startsWith('--')) || 'sherpa-assets');
  const pinned = args.find(arg => arg.startsWith('--runtime-version='))?.split('=')[1];
  const localRuntime = args.find(arg => arg.startsWith('--runtime-dir='))?.slice('--runtime-dir='.length);
  const work = await mkdtemp(join(tmpdir(), 'sherpa-assets-'));
  try {
    await mkdir(join(out, 'runtime'), { recursive: true });
    await mkdir(join(out, 'models'), { recursive: true });

    let release = { version: 'local-build', archive_url: null };
    if (localRuntime) {
      console.log(`1/3  Using the local sherpa-onnx runtime in ${localRuntime}…`);
      await cp(resolve(localRuntime), join(work, 'runtime'), { recursive: true });
    } else {
      console.log('1/3  Finding the sherpa-onnx WebAssembly runtime…');
      const info = await (await fetch(PUB_PACKAGE, { headers: { accept: 'application/vnd.pub.v2+json' } })).json();
      release = pinned ? info.versions?.find(item => item.version === pinned) : info.latest;
      if (!release?.archive_url) throw new Error(pinned ? `Runtime version ${pinned} was not found.` : 'The runtime package listing was unreadable.');
      const archive = join(work, 'runtime.tar.gz');
      const runtimeArchive = await download(release.archive_url, archive);
      if (release.archive_sha256 && createHash('sha256').update(runtimeArchive).digest('hex') !== release.archive_sha256) {
        throw new Error('The runtime download did not match its published checksum.');
      }
      await mkdir(join(work, 'runtime'));
      execFileSync('tar', ['-xzf', archive, '-C', join(work, 'runtime')]);
    }
    const runtimeFiles = {
      glue: ['sherpa-onnx-wasm-web.js', 'runtime/sherpa-onnx-wasm-web.js'],
      wasm: ['sherpa-onnx-wasm-web.wasm', 'runtime/sherpa-onnx-wasm-web.wasm'],
    };
    for (const [from, to] of Object.values(runtimeFiles)) await copyFile(await findFile(join(work, 'runtime'), from), join(out, to));
    const vadSource = await readFile(await findFile(join(work, 'runtime'), 'sherpa-onnx-vad.js'), 'utf8');
    const asrSource = await readFile(await findFile(join(work, 'runtime'), 'sherpa-onnx-asr.js'), 'utf8');
    await writeFile(join(out, 'runtime/sherpa-vad-api.js'), wrapClassicApi(vadSource, 'SherpaOnnxVadApi', ['createVad']));
    await writeFile(join(out, 'runtime/sherpa-asr-api.js'), wrapClassicApi(asrSource, 'SherpaOnnxAsrApi', ['createOnlineRecognizer']));

    console.log('2/3  Downloading Silero voice detection…');
    await download(`${MODELS}/silero_vad.onnx`, join(out, 'models/silero_vad.onnx'));

    console.log('3/3  Downloading the streaming English recognizer (~128 MB archive, ~44 MB kept)…');
    const asrArchive = join(work, 'asr.tar.bz2');
    await download(`${MODELS}/${ASR_NAME}.tar.bz2`, asrArchive);
    execFileSync('tar', ['-xjf', asrArchive, '-C', work]);
    const asrDir = join(work, ASR_NAME);
    const models = {
      encoder: 'encoder-epoch-99-avg-1.int8.onnx', decoder: 'decoder-epoch-99-avg-1.int8.onnx',
      joiner: 'joiner-epoch-99-avg-1.int8.onnx', tokens: 'tokens.txt',
    };
    for (const file of Object.values(models)) await copyFile(join(asrDir, file), join(out, 'models', file));

    const entries = {
      glue: 'runtime/sherpa-onnx-wasm-web.js', wasm: 'runtime/sherpa-onnx-wasm-web.wasm',
      vadApi: 'runtime/sherpa-vad-api.js', asrApi: 'runtime/sherpa-asr-api.js', vad: 'models/silero_vad.onnx',
      encoder: `models/${models.encoder}`, decoder: `models/${models.decoder}`, joiner: `models/${models.joiner}`, tokens: `models/${models.tokens}`,
    };
    const files = {};
    let totalBytes = 0;
    for (const [key, path] of Object.entries(entries)) {
      const data = await readFile(join(out, path));
      files[key] = { path, bytes: data.length, integrity: sri(data) };
      totalBytes += data.length;
    }
    const manifest = {
      format: 1, version: release.version, createdAt: new Date().toISOString(), totalBytes, files,
      sources: {
        runtime: { name: 'sherpa_onnx_web', version: release.version, url: release.archive_url, license: 'Apache-2.0 (sherpa-onnx). See the note on bundled third-party code in docs/ON_DEVICE_SPEECH.md.' },
        vad: { name: 'Silero VAD', url: `${MODELS}/silero_vad.onnx`, license: 'MIT' },
        asr: { name: ASR_NAME, url: `${MODELS}/${ASR_NAME}.tar.bz2`, license: 'Apache-2.0' },
      },
    };
    await writeFile(join(out, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
    console.log(`Done: ${out} (${(totalBytes / 1048576).toFixed(1)} MB, runtime ${release.version}).`);
  } finally {
    await rm(work, { recursive: true, force: true });
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
